    def get_conversation(self, conversation_id):
        """
        Return one conversation.

        Parameters
        ----------
        conversation_id : int

        Returns
        -------
        tuple | None
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT
                        id,
                        title,
                        created_at
                    FROM conversations
                    WHERE id = %s
                    """,
                    (conversation_id,)
                )
                return cursor.fetchone()

    def update_conversation_title(
        self,
        conversation_id,
        new_title
    ):
        """
        Update conversation title.
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    UPDATE conversations
                    SET title = %s
                    WHERE id = %s
                    """,
                    (new_title, conversation_id)
                )

    def delete_conversation(self, conversation_id):
        """
        Delete a conversation and all related messages.
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    DELETE FROM messages
                    WHERE conversation_id = %s
                    """,
                    (conversation_id,)
                )
                cursor.execute(
                    """
                    DELETE FROM documents
                    WHERE conversation_id = %s
                    """,
                    (conversation_id,)
                )
                cursor.execute(
                    """
                    DELETE FROM conversations
                    WHERE id = %s    
                    """,
                    (conversation_id,)
                )

    def save_message(
        self,
        conversation_id,
        role,
        content
    ):
        """
        Save a single message to the database.

        Parameters
        ----------
        conversation_id : int
        role : str
            "user" or "assistant"
        content : str
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO messages (
                        conversation_id,
                        role,
                        content
                    )
                    VALUES (%s, %s, %s)
                    """,
                    (
                        conversation_id,
                        role,
                        content
                    )
                )

    def get_messages(self, conversation_id):
        """
        Retrieve all messages for a conversation.

        Parameters
        ----------
        conversation_id : int

        Returns
        -------
        list
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT
                        role,
                        content,
                        timestamp
                    FROM messages
                    WHERE conversation_id = %s
                    ORDER BY id ASC
                    """,
                    (conversation_id,)
                )
                return cursor.fetchall()

    def delete_messages(self, conversation_id):
        """
        Delete all messages for a conversation.
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute(
                    """
                    DELETE FROM messages
                    WHERE conversation_id = %s
                    """,
                    (conversation_id,)
                )

    def clear_chat_history(self, conversation_id):
        """
        Alias for delete_messages.
        """
        return self.delete_messages(conversation_id)

    def load_chat_history(self, conversation_id):
        """
        Load conversation history in Streamlit format.

        Returns
        -------
        list
        """
        messages = self.get_messages(conversation_id)
        history = []
        for row in messages:
            role = row["role"]
            content = row["content"]
            history.append({
                "role": role,
                "content": content
            })
        return history

    def add_document(self, user_id, conversation_id, original_filename, stored_filename, file_path, vectorstore_path=None):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO documents (user_id, conversation_id, original_filename, stored_filename, file_path, vectorstore_path)
                    VALUES (%s, %s, %s, %s, %s, %s)
                    RETURNING id
                    """,
                    (user_id, conversation_id, original_filename, stored_filename, str(file_path), str(vectorstore_path) if vectorstore_path else None)
                )
                row = cursor.fetchone()
                doc_id = row[0]
                return doc_id

    def get_documents_by_conversation(self, conversation_id):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT * FROM documents
                    WHERE conversation_id = %s
                    ORDER BY created_at ASC
                    """,
                    (conversation_id,)
                )
                return [dict(row) for row in cursor.fetchall()]

    def get_documents_by_user(self, user_id):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT * FROM documents
                    WHERE user_id = %s
                    ORDER BY created_at ASC
                    """,
                    (user_id,)
                )
                return [dict(row) for row in cursor.fetchall()]

    def delete_document(self, document_id):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    DELETE FROM documents
                    WHERE id = %s
                    """,
                    (document_id,)
                )

    def delete_conversation_documents(self, conversation_id):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    DELETE FROM documents
                    WHERE conversation_id = %s
                    """,
                    (conversation_id,)
                )

    def update_vectorstore_path(self, conversation_id, vectorstore_path):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    UPDATE documents
                    SET vectorstore_path = %s
                    WHERE conversation_id = %s
                    """,
                    (str(vectorstore_path) if vectorstore_path else None, conversation_id)
                )

    def get_vectorstore_path(self, conversation_id):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT vectorstore_path FROM documents
                    WHERE conversation_id = %s AND vectorstore_path IS NOT NULL
                    LIMIT 1
                    """,
                    (conversation_id,)
                )
                row = cursor.fetchone()
                return row[0] if row else None

    def reset_database(self):
        """
        Delete all tables and recreate them.
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute("DROP TABLE IF EXISTS messages CASCADE")
                cursor.execute("DROP TABLE IF EXISTS documents CASCADE")
                cursor.execute("DROP TABLE IF EXISTS conversations CASCADE")
                cursor.execute("DROP TABLE IF EXISTS users CASCADE")
        self.initialize_database()
