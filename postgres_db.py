class PostgresRow:
    """
    A custom row object mimicking sqlite3.Row.
    Supports both positional indexing (row[0]) and key lookup (row['col']).
    Also supports unpacking (role, content = row).
    """
    def __init__(self, data, description):
        self._data = data  # tuple of values
        self._keys = [desc.name for desc in description] if description else []
        self._key_map = {name: i for i, name in enumerate(self._keys)}

    def __getitem__(self, key):
        if isinstance(key, int):
            return self._data[key]
        elif isinstance(key, str):
            idx = self._key_map.get(key)
            if idx is None:
                raise KeyError(key)
            return self._data[idx]
        else:
            raise TypeError("Row indices must be integers or strings")

    def __len__(self):
        return len(self._data)

    def __iter__(self):
        return iter(self._data)

    def keys(self):
        return self._keys

    def values(self):
        return self._data

    def items(self):
        return [(k, self._data[i]) for k, i in self._key_map.items()]

    def __repr__(self):
        return f"PostgresRow({dict(self.items())})"


def postgres_row_factory(cursor):
    """
    Psycopg 3 row factory returning PostgresRow.
    """
    description = cursor.description
    def make_row(values):
        return PostgresRow(values, description)
    return make_row


class DatabaseManager:
    """
    Handles all PostgreSQL database operations.
    """

    def __init__(self, database_name=DATABASE_URL):

        self.database_name = database_name

        self.initialize_database()

    def get_connection(self):
        """
        Create a PostgreSQL connection with custom row factory.
        """
        conn = psycopg.connect(self.database_name, row_factory=postgres_row_factory)
        return conn

    def initialize_database(self):
        """
        Create required tables if they do not exist.
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS users(
                        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name TEXT NOT NULL,
                        email TEXT UNIQUE NOT NULL,
                        password_hash TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                """)

                cursor.execute("""
                CREATE TABLE IF NOT EXISTS conversations (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    title TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY(user_id)
                    REFERENCES users(id) ON DELETE CASCADE
                )
                """)

                cursor.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    conversation_id INTEGER NOT NULL,
                    role TEXT,
                    content TEXT,
                    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY(conversation_id)
                    REFERENCES conversations(id) ON DELETE CASCADE
                )
                """)

                # Migration: Check if user_id column exists in conversations table
                # rewritten using information_schema.columns to preserve the same migration behavior.
                cursor.execute("""
                    SELECT column_name AS name
                    FROM information_schema.columns
                    WHERE table_name = 'conversations'
                """)
                columns = [row["name"] for row in cursor.fetchall()]
                if "user_id" not in columns:
                    cursor.execute("ALTER TABLE conversations ADD COLUMN user_id INTEGER NOT NULL DEFAULT 1")

                cursor.execute("""
                CREATE TABLE IF NOT EXISTS documents (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL,
                    conversation_id INTEGER NOT NULL,
                    original_filename TEXT NOT NULL,
                    stored_filename TEXT NOT NULL,
                    file_path TEXT NOT NULL,
                    vectorstore_path TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
                    FOREIGN KEY(conversation_id) REFERENCES conversations(id) ON DELETE CASCADE
                )
                """)

                # Create indexes where appropriate for foreign keys
                cursor.execute("CREATE INDEX IF NOT EXISTS idx_conversations_user_id ON conversations(user_id)")
                cursor.execute("CREATE INDEX IF NOT EXISTS idx_messages_conversation_id ON messages(conversation_id)")
                cursor.execute("CREATE INDEX IF NOT EXISTS idx_documents_user_id ON documents(user_id)")
                cursor.execute("CREATE INDEX IF NOT EXISTS idx_documents_conversation_id ON documents(conversation_id)")

    def create_user(self, name, email, password_hash):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    INSERT INTO users(name, email, password_hash)
                    VALUES (%s, %s, %s)
                    """,
                    (name, email, password_hash)
                )

    def get_user_by_email(self, email):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT * FROM users
                    WHERE email = %s
                    """,
                    (email,)
                )
                return cursor.fetchone()

    def get_user(self, user_id):
        with self.get_connection() as conn:
            with conn.cursor() as cursor:
                cursor.execute(
                    """
                    SELECT *
                    FROM users
                    WHERE id = %s
                    """,
                    (user_id,)
                )
                return cursor.fetchone()

    def show_tables(self):
        """
        Display all database tables.
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                cursor.execute("""
                    SELECT table_name AS name
                    FROM information_schema.tables
                    WHERE table_schema='public'
                """)
                return cursor.fetchall()

    def create_conversation(self, title="New Chat", user_id=None):
        """
        Create a new conversation.

        Parameters
        ----------
        title : str
            Conversation title.
        user_id : int, optional
            The user ID this conversation belongs to.

        Returns
        -------
        int
            Newly created conversation ID.
        """
        with self.get_connection() as connection:
            with connection.cursor() as cursor:
                # If user_id is not provided, try to find a default user or use a dummy ID like 1 if no user exists.
                if user_id is None:
                    try:
                        import streamlit as st
                        if "user_id" in st.session_state and st.session_state.user_id is not None:
                            user_id = st.session_state.user_id
                    except ImportError:
                        pass

                if user_id is None:
                    cursor.execute("SELECT id FROM users LIMIT 1")
                    row = cursor.fetchone()
                    if row:
                        user_id = row[0]
                    else:
                        user_id = 1 # Fallback dummy ID

                cursor.execute(
                    """
                    INSERT INTO conversations (user_id, title)
                    VALUES (%s, %s)
                    RETURNING id
                    """,
                    (user_id, title)
                )
                row = cursor.fetchone()
                conversation_id = row[0]
                return conversation_id

